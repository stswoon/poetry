const FONT = {};
for (const ch in GLYPHS) {
  const parts = GLYPHS[ch].split("|");
  const y0 = +parts[0], rows = parts.slice(1);
  const px = [];
  rows.forEach((r, j) => { for (let i = 0; i < r.length; i++) if (r[i] === "#") px.push(i, y0 + j); });
  FONT[ch] = { w: Math.max(...rows.map((r) => r.length)), px };
}
const SPACE = 4, GAP = 1;

// ширина строки в пикселях шрифта (жирный: +1 к каждой букве)
function textWidth(s) {
  let w = 0;
  for (const ch of s) {
    if (ch === "́") continue;
    const g = FONT[ch];
    w += g ? g.w + 1 + GAP : SPACE;
  }
  return Math.max(0, w - GAP);
}
function glyphW(ch) { const g = FONT[ch]; return g ? g.w + 1 + GAP : SPACE; }

// Текст жирным в масштабе sc; (x, y) — верх прописной; opt.shadow — цвет тени, opt.edge — цвет обводки.
function drawText(c, s, x, y, color, sc, opt) {
  opt = opt || {};
  const put = (col, dx, dy, grow) => {
    c.fillStyle = col;
    let cx = x;
    for (const ch of s) {
      if (ch === "́") continue;
      const g = FONT[ch];
      if (!g) { cx += SPACE * sc; continue; }
      for (let i = 0; i < g.px.length; i += 2) {
        c.fillRect(Math.round(cx + g.px[i] * sc + dx - grow), Math.round(y + g.px[i + 1] * sc + dy - grow), sc * 2 + grow * 2, sc + grow * 2);
      }
      cx += (g.w + 1 + GAP) * sc;
    }
  };
  if (opt.edge) put(opt.edge, 0, 0, Math.max(1, Math.round(sc * 0.6)));
  if (opt.shadow) put(opt.shadow, sc, sc, 0);
  put(color, 0, 0, 0);
}
