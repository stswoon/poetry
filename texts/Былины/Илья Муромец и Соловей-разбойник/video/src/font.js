const FONT = {};
for (const ch in GLYPHS) {
  const parts = GLYPHS[ch].split("|");
  const y0 = +parts[0], rows = parts.slice(1);
  const px = [];
  rows.forEach((r, j) => { for (let i = 0; i < r.length; i++) if (r[i] === "#") px.push(i, y0 + j); });
  FONT[ch] = { w: Math.max(...rows.map((r) => r.length)), px };
}
const SPACE = 3, GAP = 1;

function textWidth(s, bold) {
  let w = 0;
  for (const ch of s) {
    const g = FONT[ch];
    w += (g ? g.w + GAP : SPACE) + (g && bold ? 1 : 0);
  }
  return Math.max(0, w - GAP);
}

// Кладёт текст в контекст по целым координатам; (x, y) — верх прописной буквы.
function drawText(c, s, x, y, color, opt) {
  opt = opt || {};
  const scale = opt.scale || 1, bold = opt.bold;
  const shadow = opt.shadow;
  const put = (col, dx, dy) => {
    c.fillStyle = col;
    let cx = x + dx;
    for (const ch of s) {
      const g = FONT[ch];
      if (!g) { cx += SPACE * scale; continue; }
      for (let i = 0; i < g.px.length; i += 2) {
        c.fillRect(cx + g.px[i] * scale, y + dy + g.px[i + 1] * scale, scale * (bold ? 2 : 1), scale);
      }
      cx += (g.w + GAP + (bold ? 1 : 0)) * scale;
    }
  };
  if (shadow) put(shadow, scale, scale);
  put(color, 0, 0);
}
