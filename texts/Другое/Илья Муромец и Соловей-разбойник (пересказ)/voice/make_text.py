    (HERE / "lines.json").write_text(json.dumps(lines, ensure_ascii=False, indent=0), encoding="utf8")
    print("строк", len(lines), "кусков", len(TEXT), "знаков озвучки", sum(len(b) for b in body), "макс длина", max(len(l["text"]) for l in lines))
    for l in lines:
        print(l["n"], l["role"][:3], l["text"])


