STRESS_MAP = {w.replace("́", "").lower(): w.lower() for w in STRESS}
MAX = 60


def stress(text):
    def f(m):
        w = m.group(0)
        s = STRESS_MAP.get(w.lower())
        return w if not s else (s[0].upper() + s[1:] if w[0].isupper() else s)
    return re.sub(r"[А-Яа-яЁё]+", f, text)


def screen_lines(par):
    """Режет абзац на строки экрана: по предложениям, длинные по запятым, а там, где нужно, по словам."""
    out = []
    for sent in re.findall(r".+?(?:[.!?…]+(?:\s+—)?(?=\s|$)|$)", par):
        sent = sent.strip()
        if not sent:
            continue
        cur = ""
        for piece in re.split(r"(?<=[,:;])\s+", sent):
            cand = (cur + " " + piece).strip()
            if len(cand) <= MAX:
                cur = cand
            else:
                if cur:
                    out.append(cur)
                cur = piece
                while len(cur) > MAX:
                    cut = cur.rfind(" ", 0, MAX)
                    out.append(cur[:cut])
                    cur = cur[cut + 1:]
        if cur:
            out.append(cur)
    return out


def main():
    lines, stanzas, body = [], [], []
    for pi, (role, tag, par) in enumerate(TEXT):
        ls = screen_lines(par)
        assert " ".join(ls) == par, par[:40]
        for l in ls:
            lines.append({"n": len(lines) + 1, "text": l, "role": role, "part": pi, "stanza": pi})
        stanzas.append("\n".join(ls))
        body.append(f"#{role}\n{tag}\n{stress(par)}")
    head = """# Илья Муромец и Соловей-разбойник (пересказ)

- **Поэт:** прозаический пересказ былины; автор на странице не указан (вероятно, И. В. Карнаухова)
- **Источник:** https://nukadeti.ru/skazki/ilya_muromec_i_solovej_razbojnik
- **Примечание:** только личный просмотр, см. rights.md. Добавлены «ё» и длинные тире, текст разбит на строки экрана.

## Текст

"""
    (POEM / "poem.md").write_text(head + "\n\n".join(stanzas) + "\n", encoding="utf8")
    voice = """==================== ГОЛОС (не для озвучки) ====================

Модель:   Eleven v4
Голос: Stanislav — Deep, Empathetic and Warm (ID: ogi2DyUAKJb7CEdqqvlU)
Роли: метки #роль. Сказитель — Stanislav, Илья — Marat, Соловей — Nester Surovy, князь — Ivan Nazarov, дочка и жена — Marina.

Настройки: Stability 0.5, Similarity 0.75.

=========== ТЕКСТ ДЛЯ ОЗВУЧКИ — копировать отсюда ===========

"""
